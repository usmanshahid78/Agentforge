import type { Agent, JobDescription, KPI } from '@/types';
import { createRng, daysAgo } from './random';

const rng = createRng(7);

const spark = (base: number, drift: number, n = 14) =>
  Array.from({ length: n }, (_, i) => Math.round((base + drift * i + rng.range(-1, 1) * base * 0.06) * 10) / 10);

const kpi = (
  id: string,
  label: string,
  target: string,
  current: string,
  base: number,
  drift: number,
  direction: KPI['direction'] = 'up-good',
): KPI => ({ id, label, target, current, trend: spark(base, drift), direction });

